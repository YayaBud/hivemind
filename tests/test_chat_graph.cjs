const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const { fromState, parseTranscript } = require('../web/chat-graph.js');
const state = { AG:{codex:{name:'Codex'},claude:{name:'Claude Code'}}, FID:{codex:'summary'}, MEMS:{m1:{by:'claude',kind:'finding',short:'one',text:'A fact',topics:['auth']}}, LOGS:{codex:[{id:'s1',title:'chat',turns:[{user:'Hi',think:[{t:'check',recall:['m1']}],reply:'Done'}]}]} };
const workspace = fromState(state);
assert(workspace.nodes.some(n=>n.type==='Thought'));
assert(workspace.nodes.some(n=>n.type==='Memory'));
assert(workspace.links.every(l=>workspace.nodes.some(n=>n.id===l.source)&&workspace.nodes.some(n=>n.id===l.target)));
assert(workspace.links.some(l=>l.type==='RECALLED'&&l.target==='memory:m1'));
assert(new Set(workspace.nodes.map(n=>n.id)).size===workspace.nodes.length);
const thoughtLinks = fromState({AG:{a:{name:'A'}},FID:{a:'full'},MEMS:{},LOGS:{a:[{id:'s',turns:[{user:'Hi',think:[{t:'one'},{t:'two'}],reply:'Done'}]}]}}).links;
assert.strictEqual(thoughtLinks.filter(l=>l.type==='THOUGHT').length,1);
assert.strictEqual(thoughtLinks.filter(l=>l.type==='NEXT' && l.source.startsWith('thought:')).length,1);
assert.strictEqual(thoughtLinks.filter(l=>l.type==='LED_TO').length,1);
const dataContext = { window: {} };
vm.runInNewContext(fs.readFileSync(require.resolve('../web/data.js'), 'utf8'), dataContext);
const sample = fromState(dataContext.window.HM);
assert(Object.keys(dataContext.window.HM).every(k => sample && dataContext.window.HM[k]));
assert(sample.nodes.length > 0 && sample.links.length > 0);
assert(sample.links.some(l=>l.type==='RECALLED' && l.source.includes('thought:') && l.target.startsWith('memory:')));
assert.strictEqual(new Set(sample.links.map(l=>`${l.source}|${l.target}|${l.type}`)).size, sample.links.length);
for (const [source, words] of [['sample', ['sample']], ['offline', ['offline', 'sample']], ['empty', ['loaded', 'empty']], ['live', ['loaded', 'not streaming']]]) {
  const context = { window: { HM_SOURCE: source } };
  vm.runInNewContext(fs.readFileSync(require.resolve('../web/chat-graph.js'), 'utf8'), context);
  const label = context.window.HMChatGraph.fromState({}).sourceLabel.toLowerCase();
  words.forEach(word => assert(label.includes(word), `${source} label should include ${word}`));
}
const imported = parseTranscript('User: Hello\nAssistant: Finding: Keep this <tag>\n  continued line\nUser: Thanks');
assert.strictEqual(imported.counts.messages,3);
const mem = imported.nodes.find(n=>n.type==='Memory');
assert(mem && mem.text.includes('<tag>'));
assert(imported.nodes.some(n=>n.type==='Message'&&n.text.includes('continued line')));
assert(imported.links.some(l=>l.type==='SAVED'&&l.source.startsWith('message:')));
assert(!imported.nodes.some(n=>n.type==='Thought'));
const unknown = parseTranscript('User: https://example.test/a\nkey=value\nAssistant: okay');
assert(unknown.nodes.some(n=>n.type==='Message' && n.text.includes('https://example.test/a') && n.text.includes('key=value')));
assert.throws(()=>parseTranscript(''), /Paste/);
assert.throws(()=>parseTranscript('Speaker: hi'), /speaker labels/);
assert.throws(()=>parseTranscript('<script>alert(1)</script>\nUser: hi'), /unsupported content/);
assert.throws(()=>parseTranscript('x'.repeat(100001)), /100,000/);
assert.strictEqual(parseTranscript('**Human:** hi\n**Claude Code:** Decision: use plain text').nodes.filter(n=>n.type==='Message').length,2);
assert.strictEqual(parseTranscript('**Human**: hi\n**Claude Code**: Decision: use plain text').nodes.filter(n=>n.type==='Message').length,2);
assert.throws(()=>parseTranscript(Array.from({length:201},(_,i)=>`User: ${i}`).join('\n')), /200/);
const fenced=parseTranscript('User: show code\nAssistant: ```\nFinding: fake\nUser: fake label\n```\nDecision: real');
assert.strictEqual(fenced.nodes.filter(n=>n.type==='Memory').length, 1);
assert(fenced.nodes.some(n=>n.type==='Message'&&n.text.includes('User: fake label')));
const cyclic = fromState({AG:{a:{name:'A'}},FID:{a:'summary'},MEMS:{a:{by:'a',text:'a',supersedes:'b'},b:{by:'a',text:'b',supersedes:'a'}},LOGS:{a:[]}});
assert.strictEqual(cyclic.links.filter(l=>l.type==='SUPERSEDES').length,2);
assert.strictEqual(new Set(cyclic.links.map(l=>`${l.source}|${l.target}|${l.type}`)).size,cyclic.links.length);
console.log('chat graph tests passed');
